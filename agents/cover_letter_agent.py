import json

from django.conf import settings
from google import genai


def generate_cover_letter(user, job, resume=None):
    """
    Generate a personalized cover letter using
    Google Gemini.

    Information is taken only from:
    - User profile
    - Resume
    - Job information
    """

    # --------------------------------
    # USER PROFILE
    # --------------------------------

    try:
        profile = user.profile
    except Exception:
        profile = None

    profile_data = {
        "full_name": getattr(profile, "full_name", ""),
        "location": getattr(profile, "location", ""),
        "skills": getattr(profile, "skills", ""),
        "education": getattr(profile, "education", ""),
        "experience": getattr(profile, "experience", ""),
        "preferred_roles": getattr(
            profile,
            "preferred_roles",
            ""
        ),
        "bio": getattr(profile, "bio", ""),
    }

    # --------------------------------
    # RESUME
    # --------------------------------

    resume_text = ""

    if resume:
        resume_text = resume.extracted_text or ""

    # --------------------------------
    # JOB INFORMATION
    # --------------------------------

    job_data = {
        "title": job.title,
        "company": job.company_name,
        "location": job.location,
        "job_type": job.get_job_type_display(),
        "description": job.description,
        "requirements": job.requirements,
        "skills": job.skills,
    }

    # --------------------------------
    # PROMPT
    # --------------------------------

    prompt = f"""
You are a professional job application assistant.

Generate a professional, personalized cover letter
for the candidate applying to the job below.

IMPORTANT RULES:

1. Use ONLY information provided in the candidate profile
   and resume.

2. Never invent:
   - skills
   - education
   - experience
   - companies
   - projects
   - certifications
   - achievements
   - job titles

3. Do not claim experience that is not present.

4. Connect the candidate's actual skills and experience
   with the requirements of the job where appropriate.

5. Keep the writing professional and natural.

6. Do not mention that the letter was generated by AI.

7. Do not create fake contact information.

8. If some information is missing, simply write naturally
   without inventing it.

9. Keep the cover letter approximately 250-400 words.

10. Return ONLY the final cover letter.
   Do not return JSON.
   Do not add explanations before or after the letter.

--------------------------------
CANDIDATE PROFILE
--------------------------------

{json.dumps(profile_data, indent=2)}

--------------------------------
RESUME
--------------------------------

{resume_text}

--------------------------------
JOB INFORMATION
--------------------------------

{json.dumps(job_data, indent=2)}

--------------------------------
TASK
--------------------------------

Write the final professional cover letter.
"""

    # --------------------------------
    # GEMINI API KEY
    # --------------------------------

    api_key = getattr(
        settings,
        "GEMINI_API_KEY",
        None
    )

    if not api_key:
        raise ValueError(
            "GEMINI_API_KEY is not configured."
        )

    # --------------------------------
    # GEMINI CLIENT
    # --------------------------------

    client = genai.Client(
        api_key=api_key
    )

    # --------------------------------
    # GEMINI REQUEST
    # --------------------------------

    response = client.models.generate_content(
        model="gemini-2.5-flash",
        contents=prompt
    )

    # --------------------------------
    # RESPONSE
    # --------------------------------

    cover_letter = (
        response.text
        if response and response.text
        else ""
    )

    cover_letter = cover_letter.strip()

    if not cover_letter:
        raise ValueError(
            "Gemini returned an empty cover letter."
        )

    return cover_letter